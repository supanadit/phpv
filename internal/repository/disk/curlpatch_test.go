package disk

import (
	"archive/tar"
	"compress/gzip"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const curl712URL = "https://curl.se/download/archeology/curl-7.12.0.tar.gz"

// Regression: PHP 5.0-5.5 pin curl 7.12.0. Its Makefile.in regenerates the
// shipped Bison-1.875a getdate.c with the runner's Bison 3.x, which fails to
// compile. The patch scoped to exactly 7.12.0 must apply through phpv's real
// patcher and must not be selected for other curl versions.
func TestCurlGetdatePatch_SelectsOnly712AndApplies(t *testing.T) {
	repo := NewPatchRepository(repoPatchesDir(t), "")

	if got := repo.PatchesFor("curl", "7.12.0"); len(got) == 0 {
		t.Fatal("PatchesFor(curl, 7.12.0) = 0, want the getdate patch")
	}
	for _, v := range []string{"7.12.1", "7.20.0", "8.10.1"} {
		for _, p := range repo.PatchesFor("curl", v) {
			if p.Name == "0001-keep-shipped-getdate-c" {
				t.Fatalf("getdate patch selected for curl %s (it is 7.12.0-only)", v)
			}
		}
	}

	resp, err := http.Get(curl712URL)
	if err != nil {
		t.Fatalf("curl 7.12.0 source is required for this test: %v", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("GET %s: %s", curl712URL, resp.Status)
	}
	gz, err := gzip.NewReader(resp.Body)
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatal(err)
		}
		p := filepath.Join(root, filepath.FromSlash(hdr.Name))
		switch hdr.Typeflag {
		case tar.TypeDir:
			os.MkdirAll(p, 0o755)
		case tar.TypeReg:
			os.MkdirAll(filepath.Dir(p), 0o755)
			f, err := os.OpenFile(p, os.O_CREATE|os.O_WRONLY, os.FileMode(hdr.Mode)&0o777|0o400)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := io.Copy(f, tr); err != nil {
				t.Fatal(err)
			}
			f.Close()
		}
	}
	src := filepath.Join(root, "curl-7.12.0")
	mk := filepath.Join(src, "lib", "Makefile.in")
	before, err := os.ReadFile(mk)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(before), "$(YACC) $(YFLAGS) getdate.y;") {
		t.Fatal("pristine curl 7.12.0 no longer has the getdate regeneration rule")
	}
	applied := 0
	for _, p := range repo.PatchesFor("curl", "7.12.0") {
		if p.Apply == nil { // flags.yaml-only dirs have no patch to apply
			continue
		}
		if err := p.Apply(src); err != nil {
			t.Fatalf("applying %s: %v", p.Name, err)
		}
		applied++
	}
	if applied == 0 {
		t.Fatal("no patch was applied")
	}
	after, err := os.ReadFile(mk)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(after), "ships pre-generated by Bison 1.875a") {
		t.Fatalf("patch did not install the guard:\n%s", after)
	}
}
