package shim

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/supanadit/phpv/silo"
)

type shimKind int

const (
	kindBinary shimKind = iota
	kindPhar
	kindVendorBin
)

type shimDef struct {
	Name    string
	Kind    shimKind
	PharRel string
}

var versionRegex = regexp.MustCompile(`^[0-9]+(\.[0-9]+)*$`)

// generatedMarker identifies shims written by phpv; only files containing
// it are eligible for pruning.
const generatedMarker = "Auto-generated by phpv"

type Service struct {
	silo *silo.Service
	bin  string
}

func NewService(siloSvc *silo.Service) *Service {
	return &Service{
		silo: siloSvc,
		bin:  filepath.Join(siloSvc.GetSilo().Root, "bin"),
	}
}

func (s *Service) IsSystemMode() bool {
	return s.silo.IsSystemMode()
}

func (s *Service) SetSystemMode(enabled bool) error {
	return s.silo.SetSystemMode(enabled)
}

func (s *Service) WriteShim(def shimDef) error {
	content, err := s.renderShim(def)
	if err != nil {
		return err
	}
	path := filepath.Join(s.bin, def.Name)
	if err := os.MkdirAll(s.bin, 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o755)
}

func (s *Service) renderShim(def shimDef) (string, error) {
	var systemBlock, execLine, preExec string
	switch def.Kind {
	case kindBinary:
		systemBlock = strings.ReplaceAll(systemBinaryBlock, "{{NAME}}", def.Name)
		execLine = strings.ReplaceAll(binaryExec, "{{NAME}}", def.Name)
	case kindPhar:
		systemBlock = strings.ReplaceAll(systemPharBlock, "{{NAME}}", def.Name)
		systemBlock = strings.ReplaceAll(systemBlock, "{{PHAR_REL}}", def.PharRel)
		execLine = strings.ReplaceAll(pharExec, "{{PHAR_REL}}", def.PharRel)
		if def.Name == "composer" {
			// Composer needs special handling: a per-version global home and
			// a post-run shim refresh after `composer global ...`.
			preExec = composerHomePreExec
			execLine = strings.ReplaceAll(composerExec, "{{PHAR_REL}}", def.PharRel)
		}
	case kindVendorBin:
		systemBlock = strings.ReplaceAll(systemVendorBinBlock, "{{NAME}}", def.Name)
		execLine = strings.ReplaceAll(vendorBinExec, "{{NAME}}", def.Name)
	default:
		return "", fmt.Errorf("unknown shim kind")
	}
	out := strings.Replace(shimTemplate, "{{SYSTEM_BLOCK}}", systemBlock, 1)
	out = strings.Replace(out, "{{PRE_EXEC}}", preExec, 1)
	out = strings.Replace(out, "{{EXEC}}", execLine, 1)
	return out, nil
}

func (s *Service) WriteAll() error {
	for _, def := range defaultShims() {
		if err := s.WriteShim(def); err != nil {
			return fmt.Errorf("write shim %s: %w", def.Name, err)
		}
	}
	return nil
}

func (s *Service) WritePhar(name, pharRelPath string) error {
	return s.WriteShim(shimDef{Name: name, Kind: kindPhar, PharRel: pharRelPath})
}

func (s *Service) WriteVendorBin(name string) error {
	return s.WriteShim(shimDef{Name: name, Kind: kindVendorBin})
}

// isPHPScript reports whether the vendor bin looks like a PHP entry point
// (php shebang on its first line). Non-PHP bins are not shimmed.
func isPHPScript(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	if !scanner.Scan() {
		return false
	}
	line := strings.TrimSpace(scanner.Text())
	return strings.HasPrefix(line, "#!/usr/bin/env php") || strings.HasPrefix(line, "#!/usr/bin/php") || strings.HasPrefix(line, "#!php")
}

// pruneStaleShims removes auto-generated shims in the bin dir that the
// current generation pass did not produce. It never touches the phpv
// binary, backups, or files without the phpv marker.
func (s *Service) pruneStaleShims(generated map[string]bool) error {
	entries, err := os.ReadDir(s.bin)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, entry := range entries {
		name := entry.Name()
		if name == "phpv" || generated[name] {
			continue
		}
		path := filepath.Join(s.bin, name)
		info, err := os.Stat(path)
		if err != nil || info.IsDir() {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		if strings.Contains(string(data), generatedMarker) {
			if err := os.Remove(path); err != nil {
				return fmt.Errorf("prune stale shim %s: %w", name, err)
			}
		}
	}
	return nil
}

func (s *Service) RegenerateAll() error {
	if err := s.WriteAll(); err != nil {
		return err
	}
	generated := make(map[string]bool)
	for _, def := range defaultShims() {
		generated[def.Name] = true
	}
	// Regenerate phar shims (composer, pie, etc.) and vendor-bin shims by
	// scanning installed PHP versions. Default binary shims and phars win
	// over vendor bins with the same name.
	if s.silo == nil {
		return s.pruneStaleShims(generated)
	}
	phpDir := filepath.Join(s.silo.GetSilo().Root, "packages", "php")
	entries, err := os.ReadDir(phpDir)
	if err != nil {
		return s.pruneStaleShims(generated) // no installed PHP versions yet, not an error
	}
	seen := make(map[string]bool)
	for _, def := range defaultShims() {
		seen[def.Name] = true // default binary shims always win
	}
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		pharDir := filepath.Join(phpDir, entry.Name(), "phar")
		pharEntries, err := os.ReadDir(pharDir)
		if err != nil {
			continue
		}
		for _, pe := range pharEntries {
			if pe.IsDir() || !strings.HasSuffix(pe.Name(), ".phar") {
				continue
			}
			name := strings.TrimSuffix(pe.Name(), ".phar")
			if seen[name] {
				continue
			}
			seen[name] = true
			generated[name] = true
			if err := s.WritePhar(name, "phar/"+pe.Name()); err != nil {
				return fmt.Errorf("write phar shim %s: %w", name, err)
			}
		}
	}
	// Composer global vendor bins (one shim per tool, per active version at
	// run time via PHPV_CURRENT).
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		vendorBinDir := filepath.Join(phpDir, entry.Name(), "composer", "vendor", "bin")
		vendorEntries, err := os.ReadDir(vendorBinDir)
		if err != nil {
			continue
		}
		for _, ve := range vendorEntries {
			if ve.IsDir() {
				continue
			}
			name := ve.Name()
			if seen[name] || !isPHPScript(filepath.Join(vendorBinDir, ve.Name())) {
				continue
			}
			seen[name] = true
			generated[name] = true
			if err := s.WriteVendorBin(name); err != nil {
				return fmt.Errorf("write vendor-bin shim %s: %w", name, err)
			}
		}
	}
	return s.pruneStaleShims(generated)
}

func defaultShims() []shimDef {
	return []shimDef{
		{Name: "php", Kind: kindBinary},
		{Name: "phpize", Kind: kindBinary},
		{Name: "php-config", Kind: kindBinary},
		{Name: "php-cgi", Kind: kindBinary},
		{Name: "phpdbg", Kind: kindBinary},
	}
}

func IsValidVersion(v string) bool {
	return versionRegex.MatchString(v)
}
